export function isDigitSymbol(text: string): boolean {
  if (text.length !== 1) return false;
  const cp = text.codePointAt(0);
  if (cp === undefined) return false;
  return (cp >= 0x30 && cp <= 0x39) || (cp >= 0xff10 && cp <= 0xff19);
}

export function sanitizeRecentSymbols(
  items: readonly string[],
  max = RECENT_SYMBOLS_MAX,
): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const item of items) {
    if (!item || isDigitSymbol(item) || seen.has(item)) continue;
    seen.add(item);
    result.push(item);
    if (result.length >= max) break;
  }
  return result;
}

export function recordRecentSymbol(
  current: readonly string[],
  symbol: string,
  max = RECENT_SYMBOLS_MAX,
): string[] {
  if (!symbol || isDigitSymbol(symbol)) {
    return [...current];
  }
  const filtered = current.filter((item) => item !== symbol);
  return [symbol, ...filtered].slice(0, max);
}
